import re, pathlib, sys
exec(open(pathlib.Path(__file__).resolve().parent / 'test_encl.py').read().split("with sync_playwright() as pw:")[0])
PRE = re.search(r'PRE = """(.*?)"""', open(pathlib.Path(__file__).resolve().parent / 'test_cal2.py').read(), re.S).group(1)
with sync_playwright() as pw:
    b = pw.chromium.launch(**CHROME, args=["--no-sandbox"])
    for (w, hgt, tag) in [(390, 844, 'm'), (1400, 950, 'd')]:
        p = page(b, w, hgt, pre=PRE)
        p.click(".tab[data-tab=cal]"); p.wait_for_timeout(300)
        p.click("[data-cal-mode=grid]"); p.wait_for_timeout(600)
        cur = ".cal-month.cur"
        day10 = p.evaluate("(() => { const n = new Date(); return new Date(n.getFullYear(), n.getMonth(), 10).getTime(); })()")
        p.click(f"{cur} button.cn[data-day='{day10}']"); p.wait_for_timeout(400)
        print(tag, "day 10 sheet open:", p.is_visible("#sheet-day.open"), "| title:", p.inner_text("#dy-title"), "| sub:", p.inner_text("#dy-sub"))
        print(tag, "records:", p.locator("#dy-body .rec").count(), "| periods:", p.locator("#dy-body [data-co]").count(), "| add buttons:", p.locator("#dy-body [data-new]").count())
        p.screenshot(path=f"{out}/cd_{tag}_day10.png", full_page=False)
        p.locator("#dy-body .rec").first.click(); p.wait_for_timeout(400)
        print(tag, "record opens form:", p.is_visible("#sheet-form.open"), "| day sheet closed:", not p.is_visible("#sheet-day.open"))
        esc_close(p)
        day20 = p.evaluate("(() => { const n = new Date(); return new Date(n.getFullYear(), n.getMonth(), 20).getTime(); })()")
        day2 = p.evaluate("(() => { const n = new Date(); return new Date(n.getFullYear(), n.getMonth(), 2).getTime(); })()")
        bb = p.locator(f"{cur} .cd[data-day='{day2}']").bounding_box(); p.mouse.click(bb["x"] + bb["width"] / 2, bb["y"] + bb["height"] - 4); p.wait_for_timeout(400)
        print(tag, "empty cell area opens day 2:", p.is_visible("#sheet-day.open"), "|", p.inner_text("#dy-sub")); esc_close(p)
        p.locator(f"{cur} button.cn[data-day='{day20}']").click(); p.wait_for_timeout(400)
        print(tag, "empty day 20 sub:", p.inner_text("#dy-sub"), "| periods:", p.locator("#dy-body [data-co]").count())
        p.screenshot(path=f"{out}/cd_{tag}_day20.png", full_page=False)
        p.click("#dy-body [data-new=obs]"); p.wait_for_timeout(400)
        print(tag, "form time:", p.input_value("#fld-at")[:10], "| expected day 20:", p.evaluate(f"(() => {{ const d = new Date({day20}); return d.getFullYear() + '-' + String(d.getMonth()+1).padStart(2,'0') + '-20'; }})()"))
        p.fill("#fld-bird", "Тукан"); p.fill("#fld-note", "Проверка дня"); p.select_option("#fld-sp", index=1); p.click("#f-save"); p.wait_for_timeout(600)
        print(tag, "saved | records on 20 in db:", p.evaluate(f"__mock.db.records.filter(r => new Date(r.event_at).getDate() === 20).length"))
        p.locator(f"{cur} button.cn[data-day='{day20}']").click(); p.wait_for_timeout(400)
        print(tag, "day 20 after save:", p.inner_text("#dy-sub"), "| recs:", p.locator("#dy-body .rec").count())
        esc_close(p)
        p.locator(f"{cur} .cmore").first.click(); p.wait_for_timeout(400)
        print(tag, "+N opens day:", p.is_visible("#sheet-day.open"), p.inner_text("#dy-title"))
        esc_close(p)
        p.locator(f"{cur} .cdot").first.click(); p.wait_for_timeout(200)
        print(tag, "dot still shows tip:", p.is_visible("#cal-tip"), "| no sheet:", not p.is_visible("#sheet-day.open"))
        p.close()
    b.close()
